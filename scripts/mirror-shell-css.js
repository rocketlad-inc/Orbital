#!/usr/bin/env node
// ============================================================================
// mirror-shell-css.js — keep the JS-driven mobile shell in lockstep with CSS.
//
// THE PROBLEM THIS EXISTS FOR
//
// useIsMobile() decides the mobile shell from three clauses, one of which —
// "is this a phone/tablet OS?" — has NO media-query equivalent. A Galaxy
// Fold 7's inner screen is wider than the width breakpoint AND its browser
// does not report `hover: none`, so viewport + pointer queries cannot tell
// it apart from a large touchscreen desktop.
//
// So the JS stamps its verdict on <html data-mobile-shell>, and every shell
// rule has to be re-applied under that attribute. When a rule is missing,
// React mounts the mobile shell while the stylesheet lays out the desktop
// panel and you get BOTH at once — the split-brain layout a player reported
// on a Fold 7, with the world menu drawn twice.
//
// shellJs.css already existed and already said "GENERATED MIRROR — do not
// hand-edit". Nothing generated it. It was written by hand, and four of the
// files its own header lists as required (BodyInspector, Outliner,
// OverviewPanel, mobile.css) had zero mirrored rules. A hand-maintained
// mirror with no generator drifts the moment anyone adds a breakpoint, which
// is exactly what happened.
//
// HOW IT WORKS
//
// Finds every @media block in src/**/*.css whose condition carries the shell
// signature (`pointer: coarse` AND `hover: none`), and re-emits its contents
// with every selector prefixed by :root[data-mobile-shell]. That signature is
// precise: it is what the shell query looks like and nothing else uses it.
//
// Run from `npm run build`, so the mirror cannot rot again.
// ============================================================================

const fs = require('fs');
const path = require('path');

const SRC = path.join(__dirname, '..', 'src');
const OUT = path.join(SRC, 'styles', 'shellJs.css');
const ATTR = ':root[data-mobile-shell]';

/** Every .css under src, except the generated mirror itself. */
function cssFiles(dir, acc = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) cssFiles(p, acc);
    else if (e.name.endsWith('.css') && p !== OUT) acc.push(p);
  }
  return acc;
}

/**
 * Pull out the body of every shell @media block.
 *
 * Brace-matched rather than regexed to the closing brace: these blocks
 * contain nested rules, and a lazy regex would stop at the first `}` and
 * silently mirror a fragment — worse than mirroring nothing, because it
 * would look like it worked.
 */
function shellBlocks(css) {
  const out = [];
  const re = /@media([^{]+)\{/g;
  let m;
  while ((m = re.exec(css))) {
    const cond = m[1];
    if (!/pointer:\s*coarse/.test(cond) || !/hover:\s*none/.test(cond)) continue;
    let depth = 1;
    let i = re.lastIndex;
    while (i < css.length && depth > 0) {
      if (css[i] === '{') depth++;
      else if (css[i] === '}') depth--;
      i++;
    }
    out.push({ cond: cond.trim(), body: css.slice(re.lastIndex, i - 1) });
    re.lastIndex = i;
  }
  return out;
}

/**
 * Prefix every selector in a block with the shell attribute.
 *
 * Nested at-rules are passed through untouched rather than mangled — if
 * one ever appears the output will be visibly wrong instead of subtly
 * wrong. Comments are dropped; see the note in the body.
 */
function prefixSelectors(body) {
  // Strip comments FIRST rather than trying to match them alongside rules.
  // A comment sitting between two rules is preceded by whitespace, and an
  // alternation that only matches `/*` at the exact cursor loses to the
  // selector branch, which happily eats "whitespace + comment + selector"
  // as one token and emits `:root[data-mobile-shell] /* ... */ body {`.
  // The mirror is generated output; the reasoning lives in the source file
  // it was mirrored from, which is where anyone editing would read it.
  const clean = body.replace(/\/\*[\s\S]*?\*\//g, '');
  const out = [];
  const re = /([^{}]+)\{([^{}]*)\}/g;
  let m;
  while ((m = re.exec(clean))) {
    const sels = m[1].trim();
    const decls = m[2].trim();
    if (!sels || sels.startsWith('@')) { out.push(m[0]); continue; }
    const prefixed = sels
      .split(',')
      .map(s => s.trim())
      .filter(Boolean)
      .map(s => (s.startsWith(':root') ? s : `${ATTR} ${s}`))
      .join(',\n');
    out.push(`${prefixed} {\n  ${decls.replace(/\s*;\s*/g, ';\n  ').trim()}\n}`);
  }
  return out.join('\n\n');
}

const parts = [
  `/* ============================================================
   shellJs.css — GENERATED by scripts/mirror-shell-css.js
   DO NOT HAND-EDIT. Run \`node scripts/mirror-shell-css.js\`
   (or just \`npm run build\`) after changing any shell @media block.

   The mobile SHELL is chosen by JS (src/hooks/useIsMobile.ts), because one
   of its clauses — "is this a phone/tablet OS?" — has no media-query
   equivalent. A Fold 7's inner screen is wider than the width breakpoint
   AND its browser doesn't report \`hover: none\`, so viewport + pointer
   queries alone cannot distinguish it from a large touchscreen desktop.

   useIsMobile stamps its verdict on <html data-mobile-shell>. This file
   re-applies every shell rule under that attribute so CSS always agrees
   with JS. Without it you get the split-brain layout: the mobile shell
   AND the desktop floating panel, two copies of the same UI at once.
   ============================================================ */`,
];

let files = 0, blocks = 0;
for (const f of cssFiles(SRC).sort()) {
  const css = fs.readFileSync(f, 'utf8');
  const found = shellBlocks(css);
  if (!found.length) continue;
  files += 1;
  const rel = path.relative(SRC, f).replace(/\\/g, '/');
  for (const b of found) {
    blocks += 1;
    parts.push(`\n/* ---- mirrored from ${rel} ---- */\n/* @media ${b.cond} */`);
    parts.push(prefixSelectors(b.body));
  }
}

fs.writeFileSync(OUT, parts.join('\n') + '\n', 'utf8');
console.log(`shellJs.css: mirrored ${blocks} shell block(s) from ${files} file(s)`);
